@router.get("/scenarios", summary="Get 30 simulated validation scenarios comparing Vektor against Schedule-Only")
def get_benchmark_scenarios():
    total_count = len(SCENARIOS_DATA)
    sched_total_delay = sum(s["scheduleDelay"] for s in SCENARIOS_DATA)
    vektor_total_delay = sum(s["vektorDelay"] for s in SCENARIOS_DATA)

    sched_avg_delay = round(sched_total_delay / total_count, 1)
    vektor_avg_delay = round(vektor_total_delay / total_count, 1)

    sched_failed = sum(1 for s in SCENARIOS_DATA if "Failed" in s["scheduleOutcome"] or "Trapped" in s["scheduleOutcome"] or s["scheduleDelay"] >= 30)
    vektor_failed = sum(1 for s in SCENARIOS_DATA if "Failed" in s["vektorOutcome"] or s["vektorDelay"] >= 30)

    sched_exposure = sum(1 for s in SCENARIOS_DATA if s["scheduleExposure"])
    vektor_exposure = sum(1 for s in SCENARIOS_DATA if s["vektorExposure"])

    summary = {
        "scenarioCount": total_count,
        "averageDelayMinutes": {
            "scheduleOnly": sched_avg_delay,
            "vektor": vektor_avg_delay,
            "savingsMinutes": round(sched_avg_delay - vektor_avg_delay, 1),
            "improvementPercent": round(((sched_avg_delay - vektor_avg_delay) / sched_avg_delay) * 100, 1),
        },
        "failedJourneys": {
            "scheduleOnly": {
                "count": sched_failed,
                "percentage": round((sched_failed / total_count) * 100, 1),
            },
            "vektor": {
                "count": vektor_failed,
                "percentage": round((vektor_failed / total_count) * 100, 1),
            },
            "reductionPercent": round(((sched_failed - vektor_failed) / sched_failed) * 100, 1),
        },
        "disruptionExposure": {
            "scheduleOnly": {
                "count": sched_exposure,
                "percentage": round((sched_exposure / total_count) * 100, 1),
            },
            "vektor": {
                "count": vektor_exposure,
                "percentage": round((vektor_exposure / total_count) * 100, 1),
            },
            "reductionPercent": round(((sched_exposure - vektor_exposure) / sched_exposure) * 100, 1),
        },
        "stepFreeCompliance": "100.0% (Hard Rule: zero inaccessible edges allowed)",
    }

    return {
        "summary": summary,
        "scenarios": SCENARIOS_DATA,
    }
